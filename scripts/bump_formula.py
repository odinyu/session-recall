#!/usr/bin/env python3
"""Regenerate the Homebrew formula for a released tag.

A formula cannot use `sha256 :no_check` (that is a cask-only shortcut), so the
version and the four per-architecture checksums have to be written out. Reading
them from the release itself keeps them honest: the same bytes Homebrew will
download, hashed by GitHub.

    python3 scripts/bump_formula.py v1.9.2 [--tap]

`--tap` also copies the result into the cloned odinyu/homebrew-tap.
"""

import json
import shutil
import subprocess
import sys
from pathlib import Path

REPO = "odinyu/session-recall"
TARGETS = ["darwin-arm64", "darwin-x64", "linux-arm64", "linux-x64"]
FORMULA = Path(__file__).resolve().parent.parent / "packaging/homebrew/Formula/session-recall.rb"

TEMPLATE = '''\
# The CLI/TUI/MCP binary, distributed as a formula.
#
# Generated by scripts/bump_formula.py — edit that, not this.
#
# Why a formula and not a cask: Homebrew quarantines cask downloads
# (Library/Homebrew/cask/download.rb calls quarantine() explicitly) and never
# touches formula downloads. A quarantined ad-hoc-signed binary is why the cask
# needs that `xattr -dr com.apple.quarantine` line — a formula needs nothing:
# no notarization, no xattr, no Gatekeeper prompt.
#
# No `depends_on "bun"`: bun ships 60 MB installed, our self-contained binary is
# 27 MB, and letting Homebrew upgrade bun independently would break the tool
# silently the day an API moves.
class SessionRecall < Formula
  desc "Local, read-only full-text recall across coding-agent sessions"
  homepage "https://github.com/{repo}"
  version "{version}"
  license "MIT"

  on_macos do
    on_arm do
      url "{base}_darwin-arm64.tar.gz"
      sha256 "{darwin_arm64}"
    end
    on_intel do
      url "{base}_darwin-x64.tar.gz"
      sha256 "{darwin_x64}"
    end
  end

  on_linux do
    on_arm do
      url "{base}_linux-arm64.tar.gz"
      sha256 "{linux_arm64}"
    end
    on_intel do
      url "{base}_linux-x64.tar.gz"
      sha256 "{linux_x64}"
    end
  end

  def install
    bin.install "session-recall"
  end

  def caveats
    <<~EOS
      The index lives in the app data directory and fills on first run:
        session-recall scan

      Then, from a terminal:
        session-recall tui                 # the terminal UI
        session-recall search "keyword"    # one query, text or --json

      To let your coding agents search it too:
        session-recall setup
    EOS
  end

  test do
    # `--help` prints the command list and exits 1. Do NOT invoke the bare
    # binary here: with no subcommand it starts `serve` and blocks until killed.
    assert_match "usage", shell_output("#{{bin}}/session-recall --help 2>&1", 1)
  end
end
'''


def digests(tag: str) -> dict[str, str]:
    raw = subprocess.run(
        ["gh", "release", "view", tag, "--repo", REPO, "--json", "assets"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    assets = json.loads(raw)["assets"]
    out = {}
    for target in TARGETS:
        name = f"session-recall_{target}.tar.gz"
        match = next((a for a in assets if a["name"] == name), None)
        if match is None:
            raise SystemExit(f"release {tag} has no {name} — run the cli workflow first")
        digest = match.get("digest") or ""
        if not digest.startswith("sha256:"):
            raise SystemExit(f"{name} has no sha256 digest from the API (got {digest!r})")
        out[target] = digest.split(":", 1)[1]
    return out


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        raise SystemExit("usage: bump_formula.py vX.Y.Z [--tap]")
    tag = args[0]
    version = tag.lstrip("v")
    sha = digests(tag)
    # Assets are named session-recall_<target>.tar.gz; keep the underscore in
    # the prefix so `{base}darwin-arm64.tar.gz` resolves.
    base = f"https://github.com/{REPO}/releases/download/{tag}/session-recall"
    body = TEMPLATE.format(
        repo=REPO,
        version=version,
        base=base,
        darwin_arm64=sha["darwin-arm64"],
        darwin_x64=sha["darwin-x64"],
        linux_arm64=sha["linux-arm64"],
        linux_x64=sha["linux-x64"],
    )
    FORMULA.write_text(body)
    print(f"wrote {FORMULA} for {tag}")
    for target in TARGETS:
        print(f"  {target}: {sha[target]}")

    if "--tap" in sys.argv:
        tap = subprocess.run(
            ["brew", "--repository", "odinyu/tap"], capture_output=True, text=True, check=True
        ).stdout.strip()
        target = Path(tap) / "Formula/session-recall.rb"
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(FORMULA, target)
        print(f"copied to {target}")


if __name__ == "__main__":
    main()
